-- The slang that names the equipment groups (V3_16, V3_17). Each group's term ("lrms") and its singular
-- ("lrm") point at the group (slang.equipment_group_id) and link no equipment rows: a search finds what's in
-- the group, and the groups under it, through the tree. Before this, the 13 flat weapon families each linked
-- every item in them.
--
-- Generated from a database with V3_8 to V3_17 applied, after a slang reload ({"source": "slang"}), by
-- comparing the slang before and after. A group wins over a MegaMek name or shorthand spelled the same, so
-- five of those become groups ("ams" was only the Anti-Missile System, "c3i" only the Improved C3 Computer);
-- slang added by hand (USER) is never touched, and a term is added only if its lookup is free (it's unique).
-- Data migrations after V3_8 update what's stored; see the importers skill.

-- 1. The old family terms (their links go with them) and the names and shorthand a group takes over
DELETE FROM slang WHERE kind IN ('FAMILY', 'FAMILY_SINGULAR');
DELETE FROM slang WHERE kind IN ('ALIAS', 'SHORTHAND') AND lookup IN ('ams', 'c3i', 'cargo', 'case', 'vibroblades');

